from pydantic import BaseModel, Field
from typing import Optional, List
from datetime import datetime

# --- Customer Lookup Schemas ---
class CustomerInfo(BaseModel):
    customer_id: str
    name: str
    photo_url: Optional[str] = None
    status: str
    balance: int
    has_fingerprint: bool
    has_pin: bool

    class Config:
        from_attributes = True

class CustomerLookupResponse(BaseModel):
    success: bool
    message: str
    data: Optional[CustomerInfo] = None

# --- Charge Schemas ---
class ChargeRequest(BaseModel):
    idempotency_key: str = Field(..., description="Unique key generated by STB Kasir")
    rfid_uid: str
    amount: int = Field(..., gt=0, description="Nominal transaksi dalam Rupiah (utuh)")
    stb_device_id: str
    auth_method: str = Field("FINGERPRINT", description="FINGERPRINT | PIN_FALLBACK | ADMIN_OVERRIDE")
    pin: Optional[str] = None
    transacted_at: Optional[datetime] = None

class ChargeResponseData(BaseModel):
    transaction_id: str
    idempotency_key: str
    customer_id: str
    customer_name: str
    amount: int
    balance_before: int
    balance_after: int
    auth_method: str
    is_offline_sync: bool
    status: str
    transacted_at: datetime

class ChargeResponse(BaseModel):
    success: bool
    message: str
    data: Optional[ChargeResponseData] = None

# --- Offline Sync Schemas ---
class OfflineTransactionItem(BaseModel):
    idempotency_key: str
    rfid_uid: str
    amount: int
    stb_device_id: str
    auth_method: str
    transacted_at: datetime

class SyncOfflineRequest(BaseModel):
    stb_device_id: str
    transactions: List[OfflineTransactionItem]

class SyncResultItem(BaseModel):
    idempotency_key: str
    status: str # PROCESSED | DUPLICATE_SKIPPED | INSUFFICIENT_FUNDS | FAILED
    message: str
    transaction_id: Optional[str] = None

class SyncOfflineResponse(BaseModel):
    success: bool
    message: str
    total_batch: int
    processed_count: int
    skipped_count: int
    failed_count: int
    details: List[SyncResultItem]

# --- Admin Topup Schemas ---
class TopupRequest(BaseModel):
    customer_id: Optional[str] = None
    rfid_uid: Optional[str] = None
    amount: int = Field(..., gt=0)
    admin_device_id: str = "STB-ADMIN-01"

class TopupResponse(BaseModel):
    success: bool
    message: str
    customer_id: str
    amount_added: int
    balance_before: int
    balance_after: int
